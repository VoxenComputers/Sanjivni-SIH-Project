export const getLocalizedDayName = (date: Date, lang: SupportedLanguage): string => {
  const dayIndex = date.getDay();
  return getTranslation(lang, `weekday_${dayIndex}`);
};

export const getLocalizedDateStr = (date: Date, lang: SupportedLanguage): string => {
  const locale = getLocaleCode(lang);
  try {
    return new Intl.DateTimeFormat(locale, {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }).format(date);
  } catch {
    return date.toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' });
  }
};
